#!/usr/bin/env python3
"""Convert a FrequencyWords list into data/words-<lang>.js.

Usage: tools/build-words.py <lang> <source_50k.txt> [--top N]

The source is a FrequencyWords file (https://github.com/hermitdave/FrequencyWords),
one "word count" pair per line, most frequent first. The output keeps the top N
entries made only of the language's letters, minus the block lists in tools/.
The generated file is committed; the app never runs this tool.
"""
import argparse
import pathlib
import re

ALPHABETS = {
    "sv": "abcdefghijklmnopqrstuvwxyzåäöé",
    "en": "abcdefghijklmnopqrstuvwxyz",
}
# Single-letter entries that are real words.
SINGLE = {"sv": {"i", "å", "ö"}, "en": {"a", "i"}}

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent


def read_list(path):
    words = set()
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.startswith("#"):
                words.update(line.split())
    return words


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("lang", choices=sorted(ALPHABETS))
    ap.add_argument("source", type=pathlib.Path)
    ap.add_argument("--top", type=int, default=5000)
    args = ap.parse_args()

    letters = re.compile("[%s]+" % ALPHABETS[args.lang])
    block = read_list(HERE / "blocklist-all.txt") | read_list(HERE / f"blocklist-{args.lang}.txt")
    seen, out = set(), []
    for line in args.source.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if not parts:
            continue
        w = parts[0].lower()
        if w in seen or w in block or not letters.fullmatch(w):
            continue
        if len(w) == 1 and w not in SINGLE[args.lang]:
            continue
        seen.add(w)
        out.append(w)
        if len(out) >= args.top:
            break

    dest = ROOT / "data" / f"words-{args.lang}.js"
    dest.write_text(
        "// Generated by tools/build-words.py from FrequencyWords (hermitdave),\n"
        "// licensed CC BY-SA 4.0. See data/NOTICE.md. Most frequent first.\n"
        f'export default "{" ".join(out)}".split(" ");\n',
        encoding="utf-8",
    )
    print(f"{dest.relative_to(ROOT)}: {len(out)} words")


if __name__ == "__main__":
    main()
